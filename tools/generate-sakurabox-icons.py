"""Generate local SakuraBox vectors and legacy PNGs from one geometry definition.

Requires only the existing Python/Pillow runtime; never uses the network.
Use --output-root <empty-directory> to inspect outputs without editing resources.
"""
import argparse,json,math
from pathlib import Path
from PIL import Image,ImageDraw

ROOT=Path(__file__).resolve().parent.parent
DESIGN=json.loads((ROOT/'branding/sakurabox-design.json').read_text(encoding='utf-8'))
PINK=DESIGN['pink'];OUTLINE=[];POLY=[]
def rot(p,a):
 x,y=p;return (54+x*math.cos(a)-y*math.sin(a),54+x*math.sin(a)+y*math.cos(a))
def fmt(p):return ','.join(f'{v:.4f}'.rstrip('0').rstrip('.') for v in p)
for petal in range(5):
 angle=petal*2*math.pi/5;p0=rot(DESIGN['start'],angle)
 if not petal:OUTLINE.append('M'+fmt(p0));POLY.append(p0)
 for segment in DESIGN['petalSegments']:
  command=segment[0];points=[rot(p,angle) for p in segment[1:]];OUTLINE.append(command+','.join(fmt(p) for p in points));p3=points[-1]
  if command=='C':
   c1,c2,_=points
   for i in range(1,31):
    t=i/30;u=1-t;POLY.append(tuple(u**3*p0[k]+3*u*u*t*c1[k]+3*u*t*t*c2[k]+t**3*p3[k] for k in [0,1]))
  else:POLY.append(p3)
  p0=p3
OUTLINE=' '.join(OUTLINE)+' Z'
STAMENS=[(rot((0,-DESIGN['stamenInnerRadius']),i*2*math.pi/5),rot((0,-DESIGN['stamenOuterRadius']),i*2*math.pi/5)) for i in range(5)]
STAMEN_PATH=' '.join('M'+fmt(a)+' L'+fmt(b) for a,b in STAMENS)
DIVIDERS=[(rot(DESIGN['start'],i*2*math.pi/5),rot(tuple(x*DESIGN['dividerInnerRadius']/15 for x in DESIGN['start']),i*2*math.pi/5)) for i in range(5)]
DIVIDER_PATH=' '.join('M'+fmt(a)+' L'+fmt(b) for a,b in DIVIDERS)
dot=DESIGN['centerDotRadius'];DOT=f'M{54-dot},54 a{dot},{dot} 0,1 0,{dot*2} 0 a{dot},{dot} 0,1 0,{-dot*2} 0'

def vector(color,small=False,stroke=None):
 stroke=stroke or DESIGN['launcherStroke'];size=24 if small else 108
 transform=' android:translateX="-5.28" android:translateY="-5.28" android:scaleX="0.32" android:scaleY="0.32"' if small else ''
 return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate-sakurabox-icons.py; one shared SakuraBox contour. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp" android:height="{size}dp"
    android:viewportWidth="{size}" android:viewportHeight="{size}">
    <group{transform}>
        <path android:name="outline" android:fillColor="@android:color/transparent"
            android:strokeColor="{color}" android:strokeWidth="{stroke}"
            android:strokeLineCap="round" android:strokeLineJoin="round"
            android:pathData="{OUTLINE}" />
        <path android:fillColor="@android:color/transparent" android:strokeColor="{color}"
            android:strokeWidth="{stroke}" android:strokeLineCap="round"
            android:pathData="{DIVIDER_PATH} {STAMEN_PATH}" />
        <path android:fillColor="{color}" android:pathData="{DOT}" />
    </group>
</vector>
'''

def render(size,color=PINK,background=None,stroke=None,legacy=False,round_mask=False):
 stroke=stroke or DESIGN['launcherStroke']
 scale=4;im=Image.new('RGBA',(size*scale,size*scale),background or (0,0,0,0));d=ImageDraw.Draw(im)
 factor=size*scale/(72 if legacy else 108);shift=18 if legacy else 0
 def point(p):return tuple((v-shift)*factor for v in p)
 width=max(1,round(stroke*factor));pts=[point(p) for p in POLY];d.line(pts+[pts[0]],fill=color,width=width,joint='curve')
 # Union sampled round caps to avoid Pillow polyline seams at acute joins.
 for x,y in pts:d.ellipse((x-width/2,y-width/2,x+width/2,y+width/2),fill=color)
 for a,b in STAMENS+DIVIDERS:
  a,b=point(a),point(b);d.line([a,b],fill=color,width=width)
  for x,y in [a,b]:d.ellipse((x-width/2,y-width/2,x+width/2,y+width/2),fill=color)
 cx,cy=point((54,54));radius=DESIGN['centerDotRadius']*factor;d.ellipse((cx-radius,cy-radius,cx+radius,cy+radius),fill=color)
 if round_mask:
  mask=Image.new('L',im.size,0);ImageDraw.Draw(mask).ellipse((0,0,im.width-1,im.height-1),fill=255);im.putalpha(mask)
 return im.resize((size,size),Image.Resampling.LANCZOS)

def generate(dest):
 files=[]
 def write(name,data):
  p=dest/name;p.parent.mkdir(parents=True,exist_ok=True)
  p.write_bytes(data if isinstance(data,bytes) else data.encode('utf-8'));files.append(name)
 def png(name,image):
  import io
  b=io.BytesIO();image.save(b,format='PNG',optimize=True);write(name,b.getvalue())
 res='app/src/main/res/'
 for name,color,small,stroke in [
  ('ic_sakura_launcher_foreground',PINK,False,DESIGN['launcherStroke']),('ic_sakura_monochrome','#FFFFFF',False,DESIGN['launcherStroke']),
  ('ic_sakura_logo',PINK,False,DESIGN['launcherStroke']),('ic_sakura_shortcut',PINK,True,3.3),
  ('ic_sakura_notification','#FFFFFF',True,3.3),
  ('ic_service_idle','#FFFFFF',True,3.3),('ic_service_busy','#FFFFFF',True,3.3),('ic_service_active','#FFFFFF',True,3.3)]:
  write(res+'drawable/'+name+'.xml',vector(color,small,stroke))
 for name,drawable,alpha1,alpha2 in [('stopped','idle',0.65,1),('connecting','idle',1,0.55),('connected','busy',0.55,1),('stopping','busy',1,0.55)]:
  write(res+f'drawable/ic_service_{name}.xml',f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Preserve the ServiceButton animated-vector contract and callbacks. -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt" android:drawable="@drawable/ic_service_{drawable}">
    <target android:name="outline">
        <aapt:attr name="android:animation">
            <objectAnimator android:propertyName="strokeAlpha" android:valueFrom="{alpha1}"
                android:valueTo="{alpha2}" android:valueType="floatType"
                android:duration="@android:integer/config_mediumAnimTime"
                android:interpolator="@android:interpolator/fast_out_slow_in" />
        </aapt:attr>
    </target>
</animated-vector>
''')
 for api in [26,33]:
  mono='\n    <monochrome android:drawable="@drawable/ic_sakura_monochrome" />' if api>=33 else ''
  xml=f'''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_sakura_launcher_foreground" />{mono}
</adaptive-icon>
'''
  for name in ['ic_launcher','ic_launcher_round']:write(res+f'mipmap-anydpi-v{api}/{name}.xml',xml)
  if api==26:write(res+'drawable-v26/ic_qu_shadowsocks_launcher.xml',xml)
 write(res+'drawable/ic_sakura_shortcut_background.xml','''<?xml version="1.0" encoding="utf-8"?>
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="oval">
    <solid android:color="#FFFFFF" />
    <size android:width="44dp" android:height="44dp" />
</shape>
''')
 write(res+'drawable/ic_qu_shadowsocks_launcher.xml','''<?xml version="1.0" encoding="utf-8"?>
<!-- Existing shortcut resource ID retained for pinned shortcut compatibility. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@drawable/ic_sakura_shortcut_background"
        android:left="2dp" android:top="2dp" android:right="2dp" android:bottom="2dp" />
    <item android:drawable="@drawable/ic_sakura_shortcut"
        android:left="12dp" android:top="12dp" android:right="12dp" android:bottom="12dp" />
</layer-list>
''')
 for density,scale in [('mdpi',1),('hdpi',1.5),('xhdpi',2),('xxhdpi',3),('xxxhdpi',4)]:
  base=res+f'mipmap-{density}/'
  png(base+'ic_launcher.png',render(round(48*scale),background='#FFFFFF',legacy=True))
  png(base+'ic_launcher_round.png',render(round(48*scale),background='#FFFFFF',legacy=True,round_mask=True))
  png(base+'ic_launcher_foreground.png',render(round(108*scale)))
 png('app/src/main/ic_launcher-playstore.png',render(512,background='#FFFFFF',legacy=True))
 write('branding/sakurabox-symbol.svg',f'''<svg xmlns="http://www.w3.org/2000/svg" width="108" height="108" viewBox="0 0 108 108">
  <title>SakuraBox five-petal cherry blossom</title>
  <g fill="none" stroke="{PINK}" stroke-width="{DESIGN['launcherStroke']}" stroke-linecap="round" stroke-linejoin="round">
    <path d="{OUTLINE}" />
    <path d="{DIVIDER_PATH} {STAMEN_PATH}" />
  </g>
  <circle cx="54" cy="54" r="{DESIGN['centerDotRadius']}" fill="{PINK}" />
</svg>
''')
 return files

if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--output-root',type=Path,default=ROOT);args=p.parse_args()
 print(json.dumps({'generated':generate(args.output_root.resolve())},indent=2))
